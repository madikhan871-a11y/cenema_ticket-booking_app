class Movie {
  final String id;
  final String title;
  final String genre;
  final String duration;
  final String rating;
  final String poster;
  final String description;
  final double score;

  const Movie({
    required this.id,
    required this.title,
    required this.genre,
    required this.duration,
    required this.rating,
    required this.poster,
    required this.description,
    required this.score,
  });
}